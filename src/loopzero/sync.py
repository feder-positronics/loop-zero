def _substitute_skill(
    text: str, profile: Profile, source: Path, consumer_skills: set[str]
) -> str:
    values = _skill_values(profile, consumer_skills)

    def replace(match: re.Match[str]) -> str:
        name = match.group("name")
        if name not in values:
            if name in {"package.product_name", "package.commit_identity"}:
                raise ConfigError([f"[package].{name.removeprefix('package.')}: required by {source}"])
            raise ConfigError([f"{source}: unknown skill template token {name!r}"])
        return values[name]

    rendered = _SKILL_TOKEN.sub(replace, text)
    if "{{" in rendered or "}}" in rendered:
        raise ConfigError([f"{source}: unresolved or malformed skill template token"])
    return rendered


def _read_skill_source(path: Path) -> str:
    try:
        metadata = os.lstat(path)
        if stat.S_ISLNK(metadata.st_mode) or not stat.S_ISREG(metadata.st_mode):
            raise ConfigError([f"skill source {path}: must be a regular file"])
        return path.read_text(encoding="utf-8")
    except FileNotFoundError:
        raise ConfigError([f"skill source {path}: missing"]) from None
    except (OSError, UnicodeError) as exc:
        raise ConfigError([f"skill source {path}: cannot read: {exc}"]) from None


def _skill_files(
    profile: Profile, shadowed: set[str], consumer_skills: set[str]
) -> tuple[list[Rendered], dict[str, dict[str, object]]]:
    source_root = profile.snapshot_dir / "skills"
    if not source_root.is_dir() or source_root.is_symlink():
        raise ConfigError([f"skill source {source_root}: must be a real directory"])
    rendered: list[Rendered] = []
    records: dict[str, dict[str, object]] = {}

    def add_skill(name: str, directory: Path, *, vendor: bool) -> None:
        if name in shadowed:
            return
        files: list[str] = []
        digests: dict[str, str] = {}
        for source in sorted(directory.rglob("*"), key=lambda item: item.as_posix()):
            relative_source = source.relative_to(directory)
            if source.is_symlink():
                raise ConfigError([f"skill source {source}: symlinks are forbidden"])
            if source.name in {"PIN", "OVERLAY.md"} or source.is_dir():
                continue
            if not source.is_file():
                raise ConfigError([f"skill source {source}: must be a regular file"])
            content = _read_skill_source(source)
            if vendor and source.name == "SKILL.md":
                overlay_path = directory / "OVERLAY.md"
                overlay = _read_skill_source(overlay_path)
                if SKILL_OVERLAY_BEGIN in content or SKILL_OVERLAY_END in content:
                    raise ConfigError([f"skill source {source}: reserved overlay delimiter is forbidden"])
                if SKILL_OVERLAY_BEGIN in overlay or SKILL_OVERLAY_END in overlay:
                    raise ConfigError([f"skill source {overlay_path}: reserved overlay delimiter is forbidden"])
                content = (
                    content
                    + ("" if content.endswith("\n") else "\n")
                    + "\n"
                    + SKILL_OVERLAY_BEGIN
                    + "\n"
                    + overlay
                    + ("" if overlay.endswith("\n") else "\n")
                    + SKILL_OVERLAY_END
                    + "\n"
                )
            elif not vendor and source.suffix == ".md":
                content = _substitute_skill(content, profile, source, consumer_skills)
            target = profile.skills_dir / name / relative_source
            rendered.append(Rendered(target, content, False))
            relative_name = relative_source.as_posix()
            files.append(relative_name)
            digests[relative_name] = hashlib.sha256(content.encode("utf-8")).hexdigest()
        if "SKILL.md" not in files:
            raise ConfigError([f"skill source {directory}: missing SKILL.md"])
        records[name] = {
            "source": "vendor" if vendor else "governance",
            "files": files,
            "sha256": digests,
        }

    for directory in sorted(source_root.iterdir(), key=lambda item: item.name):
        if directory.name == "vendor":
            continue
        if directory.is_symlink():
            raise ConfigError([f"skill source {directory}: symlinks are forbidden"])
        if not directory.is_dir():
            continue
        if (directory / "SKILL.md").is_file():
            add_skill(directory.name, directory, vendor=False)

    vendor_root = source_root / "vendor"
    if vendor_root.is_dir() and not vendor_root.is_symlink():
        for directory in sorted(vendor_root.iterdir(), key=lambda item: item.name):
            if directory.is_symlink():
                raise ConfigError([f"skill source {directory}: symlinks are forbidden"])
            if not directory.is_dir():
                continue
            if (directory / "SKILL.md").is_file():
                if directory.name in records:
                    raise ConfigError([f"duplicate rendered skill name: {directory.name}"])
                add_skill(directory.name, directory, vendor=True)
    readme_source = source_root / "README.md"
    readme_content = _substitute_skill(
        _read_skill_source(readme_source), profile, readme_source, consumer_skills
    )
    rendered.append(Rendered(profile.skills_dir / "README.md", readme_content, False))
    return rendered, records


def _skills_manifest(
    profile: Profile,
    records: dict[str, dict[str, object]],
    shadowed: set[str],
    all_names: set[str],
    canonical_files: list[Rendered],
) -> str:
    canonical_entries = {
        item.path.as_posix(): {
            "type": "regular_file",
            "sha256": hashlib.sha256(item.content.encode("utf-8")).hexdigest(),
        }
        for item in canonical_files
    }
    canonical_directories = sorted(
        {
            parent.as_posix()
            for item in canonical_files
            for parent in item.path.parents
            if parent != profile.skills_dir and parent.is_relative_to(profile.skills_dir)
        }
    )
    mirror_entries = {
        (mirror / name).as_posix(): {
            "type": "symlink",
            "target": os.path.relpath(profile.skills_dir / name, mirror),
        }
        for mirror in profile.skill_mirrors
        for name in sorted(all_names)
    }
    payload = {
        "schema_version": 2,
        "core_revision": profile.core_revision,
        "skills_dir": profile.skills_dir.as_posix(),
        "skill_mirrors": [path.as_posix() for path in profile.skill_mirrors],
        "canonical_files": canonical_entries,
        "canonical_directories": {
            path: {"type": "directory"} for path in canonical_directories
        },
        "mirror_links": mirror_entries,
        "skills": records,
        "shadowed_consumer_skills": sorted(shadowed),
        "mirrored_skills": sorted(all_names),
    }
    return json.dumps(payload, indent=2, sort_keys=True) + "\n"


def render(
    profile: Profile,
    *,
    shadowed_skills: set[str] | None = None,
    consumer_skills: set[str] | None = None,
    available_skills: set[str] | None = None,
) -> list[Rendered]:
    shadowed = set(shadowed_skills or ())
    consumer = set(consumer_skills or ())
    available = set(available_skills if available_skills is not None else consumer)
    files = [
        Rendered(Path("AGENTS.md"), _pointer_block(profile, "codex"), True),
        Rendered(Path("CLAUDE.md"), _pointer_block(profile, "claude"), True),
        Rendered(Path(".cursor/rules/loopzero.mdc"), _cursor_rule(profile), False),
        Rendered(Path(".loopzero/claude-settings-fragment.json"), _claude_settings_fragment(profile), False),
    ]
    skill_files, records = _skill_files(profile, shadowed, available)
    files.extend(skill_files)
    all_names = set(records) | consumer
    files.append(
        Rendered(
            SKILLS_MANIFEST_PATH,
            _skills_manifest(profile, records, shadowed, all_names, skill_files),
            False,
        )
    )
    for mirror in profile.skill_mirrors:
        for name in sorted(all_names):
            target = os.path.relpath(profile.skills_dir / name, mirror)
            files.append(Rendered(mirror / name, target, False, symlink=True))
    files.append(Rendered(Path(".loopzero/generated.json"), _manifest(profile, files), False))
    for rendered in files:
        if rendered.symlink:
            continue
        marker_lines = [
            line
            for line in rendered.content.splitlines()
            if any(marker in line for marker in MANAGED_MARKER_TOKENS)
        ]
        expected = [BEGIN, END] if rendered.managed_block else []
        if marker_lines != expected:
            raise ConfigError([f"unexpected managed marker in {rendered.path}"])
    return files


def _line_value(line: str) -> str:
    if line.endswith("\r\n"):
        return line[:-2]
    if line.endswith(("\r", "\n")):
        return line[:-1]
    return line


def _apply_block(existing: str, block: str, newline: str = "\n") -> str:
    lines = existing.splitlines(keepends=True)
    values = [_line_value(line) for line in lines]
    for value in values:
        if (BEGIN in value and value != BEGIN) or (END in value and value != END):
            raise ConfigError(["managed markers must be exact standalone lines"])
    begins = [index for index, value in enumerate(values) if value == BEGIN]
    ends = [index for index, value in enumerate(values) if value == END]
    if len(begins) != len(ends) or len(begins) not in (0, 1):
        raise ConfigError(["managed markers must contain zero or one matched pair"])
    if begins and begins[0] >= ends[0]:
        raise ConfigError(["managed markers are reversed or malformed"])

    block = block.replace("\n", newline)
    if begins:
        head = "".join(lines[: begins[0]])
        tail = "".join(lines[ends[0] + 1 :]).lstrip("\r\n")
        return head + block + (newline + tail if tail else "")
    if existing and not existing.endswith(("\r", "\n")):
        existing += newline
    return existing + (newline if existing else "") + block


def _validate_relative(relative: Path) -> None:
    if relative.is_absolute() or not relative.parts or ".." in relative.parts:
        raise ConfigError([f"generated target {relative}: must remain inside the repository"])


def _safe_target(root: Path, relative: Path) -> Path:
    """Validate a generated target for compatibility callers."""
    _validate_relative(relative)
    try:
        root = root.resolve(strict=True)
    except OSError as exc:
        raise ConfigError([f"repository root is unavailable: {exc}"]) from None
    target = root / relative
    try:
        target.resolve(strict=False).relative_to(root)
    except (OSError, ValueError):
        raise ConfigError([f"generated target {relative}: resolves outside the repository"]) from None

    current = root
    missing = False
    for index, part in enumerate(relative.parts):
        current = current / part
        if missing:
            continue
        try:
            metadata = os.lstat(current)
        except FileNotFoundError:
            missing = True
            continue
        except OSError as exc:
            raise ConfigError([f"generated target {relative}: cannot inspect {current}: {exc}"]) from None
        if stat.S_ISLNK(metadata.st_mode):
            raise ConfigError([f"generated target {relative}: symlink component {current} is forbidden"])
        final = index == len(relative.parts) - 1
        if final and not stat.S_ISREG(metadata.st_mode):
            raise ConfigError([f"generated target {relative}: existing target must be a regular file"])
        if not final and not stat.S_ISDIR(metadata.st_mode):
            raise ConfigError([f"generated target {relative}: parent {current} is not a directory"])
    return target


def _identity(metadata: os.stat_result) -> tuple[int, int]:
    return metadata.st_dev, metadata.st_ino


def _open_absolute_directory(path: Path) -> int:
    """Open an absolute directory by no-follow traversal from ``/``."""
    if not path.is_absolute():
        raise ConfigError([f"repository root {path}: must be absolute"])
    descriptor = os.open("/", _DIRECTORY_FLAGS)
    try:
        for part in path.parts[1:]:
            metadata = os.stat(part, dir_fd=descriptor, follow_symlinks=False)
            if stat.S_ISLNK(metadata.st_mode) or not stat.S_ISDIR(metadata.st_mode):
                raise ConfigError([f"repository path component {part!r} is not a real directory"])
            child = os.open(part, _DIRECTORY_FLAGS, dir_fd=descriptor)
            if _identity(os.fstat(child)) != _identity(metadata):
                os.close(child)
                raise ConfigError([f"repository path component {part!r} changed concurrently"])
            os.close(descriptor)
            descriptor = child
        return descriptor
    except ConfigError:
        os.close(descriptor)
        raise
    except OSError as exc:
        os.close(descriptor)
        raise ConfigError([f"repository root is unavailable: {exc}"]) from None


def _verify_directory(handle: DirectoryHandle) -> None:
    try:
        metadata = os.fstat(handle.descriptor)
    except OSError as exc:
        raise ConfigError([f"generated parent {handle.relative}: cannot re-verify: {exc}"]) from None
    if not stat.S_ISDIR(metadata.st_mode) or _identity(metadata) != handle.identity:
        raise ConfigError([f"generated parent {handle.relative}: changed concurrently"])


def _open_parent(root_descriptor: int, relative: Path, *, create: bool) -> DirectoryHandle | None:
    """Open a target parent component-by-component relative to the root fd."""
    _validate_relative(relative)
    descriptor = os.dup(root_descriptor)
    parent = relative.parent
    walked = Path()
    created_paths: list[Path] = []
    try:
        for part in parent.parts:
            if part in ("", "."):
                continue
            walked /= part
            try:
                metadata = os.stat(part, dir_fd=descriptor, follow_symlinks=False)
            except FileNotFoundError:
                if not create:
                    os.close(descriptor)
                    return None
                os.mkdir(part, 0o755, dir_fd=descriptor)
                os.fsync(descriptor)
                created_paths.append(walked)
                metadata = os.stat(part, dir_fd=descriptor, follow_symlinks=False)
            if stat.S_ISLNK(metadata.st_mode) or not stat.S_ISDIR(metadata.st_mode):
                raise ConfigError(
                    [f"generated target {relative}: symlink or non-directory parent component {part}"]
                )
            child = os.open(part, _DIRECTORY_FLAGS, dir_fd=descriptor)
            if _identity(os.fstat(child)) != _identity(metadata):
                os.close(child)
                raise ConfigError([f"generated target {relative}: parent changed concurrently"])
            os.close(descriptor)
            descriptor = child
        metadata = os.fstat(descriptor)
        return DirectoryHandle(parent, descriptor, _identity(metadata), tuple(created_paths))
    except ConfigError:
        os.close(descriptor)
        raise
    except OSError as exc:
        os.close(descriptor)
        raise ConfigError([f"generated target {relative}: cannot open parent: {exc}"]) from None


def _read_name(
    handle: DirectoryHandle, name: str, display: Path, *, allow_symlink: bool = False
) -> TargetState | None:
    _verify_directory(handle)
    try:
        metadata = os.stat(name, dir_fd=handle.descriptor, follow_symlinks=False)
    except FileNotFoundError:
        return None
    except OSError as exc:
        raise ConfigError([f"generated target {display}: cannot inspect: {exc}"]) from None
    if stat.S_ISLNK(metadata.st_mode):
        if not allow_symlink:
            raise ConfigError([f"generated target {display}: symlink target is forbidden"])
        try:
            target = os.readlink(name, dir_fd=handle.descriptor)
        except OSError as exc:
            raise ConfigError([f"generated target {display}: cannot read symlink: {exc}"]) from None
        return TargetState(os.fsencode(target), None, True)
    if not stat.S_ISREG(metadata.st_mode):
        raise ConfigError([f"generated target {display}: existing target must be a regular file"])
    try:
        descriptor = os.open(
            name,
            os.O_RDONLY | os.O_NONBLOCK | os.O_NOFOLLOW | os.O_CLOEXEC,
            dir_fd=handle.descriptor,
        )
    except OSError as exc:
        raise ConfigError([f"generated target {display}: cannot open without following links: {exc}"]) from None
    try:
        opened = os.fstat(descriptor)
        if not stat.S_ISREG(opened.st_mode) or _identity(opened) != _identity(metadata):
            raise ConfigError([f"generated target {display}: existing target must be a regular file"])
        flags = fcntl.fcntl(descriptor, fcntl.F_GETFL)
        fcntl.fcntl(descriptor, fcntl.F_SETFL, flags & ~os.O_NONBLOCK)
        chunks: list[bytes] = []
        while chunk := os.read(descriptor, 1024 * 1024):
            chunks.append(chunk)
        return TargetState(b"".join(chunks), stat.S_IMODE(opened.st_mode))
    except OSError as exc:
        raise ConfigError([f"generated target {display}: cannot read: {exc}"]) from None
    finally:
        os.close(descriptor)


def _read_relative(
    root_descriptor: int, relative: Path, *, allow_symlink: bool = False
) -> TargetState | None:
    handle = _open_parent(root_descriptor, relative, create=False)
    if handle is None:
        return None
    try:
        return _read_name(handle, relative.name, relative, allow_symlink=allow_symlink)
    finally:
        os.close(handle.descriptor)


def _expected(rendered: Rendered, original: bytes | None) -> bytes:
    if rendered.symlink:
        return os.fsencode(rendered.content)
    newline = "\r\n" if original is not None and b"\r\n" in original else "\n"
    generated = rendered.content.replace("\n", newline)
    if not rendered.managed_block:
        return generated.encode("utf-8")
    try:
        existing = original.decode("utf-8") if original is not None else ""
    except UnicodeDecodeError as exc:
        raise ConfigError([f"{rendered.path}: existing file is not UTF-8: {exc}"]) from None
    return _apply_block(existing, rendered.content, newline).encode("utf-8")


def _manifest_relative_path(value: object, label: str) -> Path:
    if not isinstance(value, str):
        raise ValueError(f"{label} must be a string")
    path = Path(value)
    if path.is_absolute() or not path.parts or ".." in path.parts or path == Path("."):
        raise ValueError(f"{label} must be repository-relative without traversal")
    return path


def _manifest_digest(value: object, label: str) -> str:
    if not isinstance(value, str) or not re.fullmatch(r"[0-9a-f]{64}", value):
        raise ValueError(f"{label} must be a lowercase SHA-256 digest")
    return value


def _read_skills_manifest(root_descriptor: int) -> SkillsOwnership:
    state = _read_relative(root_descriptor, SKILLS_MANIFEST_PATH)
    if state is None:
        return SkillsOwnership(None, {}, frozenset(), {}, frozenset())
    try:
        payload = json.loads(state.content.decode("utf-8"))
        if not isinstance(payload, dict):
            raise ValueError("top level must be an object")
        skills_dir = _manifest_relative_path(payload["skills_dir"], "skills_dir")
        mirrors_raw = payload["skill_mirrors"]
        if not isinstance(mirrors_raw, list):
            raise ValueError("skill_mirrors must be an array")
        mirrors = tuple(
            _manifest_relative_path(value, f"skill_mirrors[{index}]")
            for index, value in enumerate(mirrors_raw)
        )
        if len(set(mirrors)) != len(mirrors) or skills_dir in mirrors:
            raise ValueError("skill directories must be distinct")
        skills = payload["skills"]
        if not isinstance(skills, dict) or any(not isinstance(name, str) for name in skills):
            raise ValueError("skills must be an object")
        canonical_from_skills: dict[Path, str] = {}
        for name, record in skills.items():
            if not _SKILL_NAME.fullmatch(name) or not isinstance(record, dict):
                raise ValueError(f"skill {name!r} has an invalid record")
            files = record.get("files")
            digests = record.get("sha256")
            if (
                not isinstance(files, list)
                or not files
                or not isinstance(digests, dict)
                or set(files) != set(digests)
            ):
                raise ValueError(f"skill {name!r} must record matching files and digests")
            for relative_value in files:
                relative = _manifest_relative_path(
                    relative_value, f"skills.{name}.files entry"
                )
                path = skills_dir / name / relative
                canonical_from_skills[path] = _manifest_digest(
                    digests[relative_value], f"skills.{name}.sha256.{relative_value}"
                )
        mirrored = payload.get("mirrored_skills")
        if not isinstance(mirrored, list) or any(
            not isinstance(name, str) or not _SKILL_NAME.fullmatch(name)
            for name in mirrored
        ):
            raise ValueError("mirrored_skills must contain canonical names")
        expected_mirror_links = {
            mirror / name: os.path.relpath(skills_dir / name, mirror)
            for mirror in mirrors
            for name in mirrored
        }

        if payload.get("schema_version") == 2:
            canonical_raw = payload.get("canonical_files")
            directories_raw = payload.get("canonical_directories")
            mirrors_entries_raw = payload.get("mirror_links")
            if (
                not isinstance(canonical_raw, dict)
                or not isinstance(directories_raw, dict)
                or not isinstance(mirrors_entries_raw, dict)
            ):
                raise ValueError(
                    "schema v2 requires canonical_files, canonical_directories, and mirror_links objects"
                )
            canonical: dict[Path, str] = {}
            for raw_path, entry in canonical_raw.items():
                path = _manifest_relative_path(raw_path, "canonical_files path")
                try:
                    path.relative_to(skills_dir)
                except ValueError:
                    raise ValueError(f"canonical file {path} is outside skills_dir") from None
                if not isinstance(entry, dict) or entry.get("type") != "regular_file":
                    raise ValueError(f"canonical file {path} must have regular_file type")
                canonical[path] = _manifest_digest(
                    entry.get("sha256"), f"canonical_files.{raw_path}.sha256"
                )
            if any(canonical.get(path) != digest for path, digest in canonical_from_skills.items()):
                raise ValueError("canonical_files does not match skill file records")
            if set(canonical) - set(canonical_from_skills) != {skills_dir / "README.md"}:
                raise ValueError("canonical_files may additionally own only the canonical README")

            directories: set[Path] = set()
            for raw_path, entry in directories_raw.items():
                path = _manifest_relative_path(raw_path, "canonical_directories path")
                if (
                    not path.is_relative_to(skills_dir)
                    or path == skills_dir
                    or not isinstance(entry, dict)
                    or entry.get("type") != "directory"
                ):
                    raise ValueError(f"canonical directory {path} is invalid")
                directories.add(path)
            required_directories = {
                parent
                for path in canonical
                for parent in path.parents
                if parent != skills_dir and parent.is_relative_to(skills_dir)
            }
            if directories != required_directories:
                raise ValueError("canonical_directories does not match canonical file parents")

            mirror_links: dict[Path, str] = {}
            for raw_path, entry in mirrors_entries_raw.items():
                path = _manifest_relative_path(raw_path, "mirror_links path")
                if path.parent not in mirrors:
                    raise ValueError(f"mirror link {path} is outside manifested mirror directories")
                if not isinstance(entry, dict) or entry.get("type") != "symlink":
                    raise ValueError(f"mirror link {path} must have symlink type")
                target = entry.get("target")
                if not isinstance(target, str) or not target:
                    raise ValueError(f"mirror link {path} must record its exact target")
                mirror_links[path] = target
            if mirror_links != expected_mirror_links:
                raise ValueError("mirror_links does not match manifested directories and names")
        elif "schema_version" not in payload:
            # Safely migrate the head's v1 format: it already recorded exact
            # skill file digests plus canonical and mirror directories.
            canonical = canonical_from_skills
            directories = {
                parent
                for path in canonical
                for parent in path.parents
                if parent != skills_dir and parent.is_relative_to(skills_dir)
            }
            mirror_links = expected_mirror_links
        else:
            raise ValueError("unsupported schema_version")
        return SkillsOwnership(
            skills_dir, canonical, frozenset(directories), mirror_links, frozenset(skills)
        )
    except (KeyError, TypeError, ValueError, UnicodeError) as exc:
        raise ConfigError([f"{SKILLS_MANIFEST_PATH}: invalid rendered manifest: {exc}"]) from None


def _existing_skill_names(profile: Profile, root_descriptor: int) -> set[str]:
    probe = profile.skills_dir / ".loopzero-probe"
    handle = _open_parent(root_descriptor, probe, create=False)
    if handle is None:
        return set()
    try:
        names: set[str] = set()
        for name in os.listdir(handle.descriptor):
            metadata = os.stat(name, dir_fd=handle.descriptor, follow_symlinks=False)
            if stat.S_ISLNK(metadata.st_mode):
                raise ConfigError(
                    [f"canonical skill {profile.skills_dir / name}: symlink directories are forbidden"]
                )
            if stat.S_ISDIR(metadata.st_mode):
                names.add(name)
        return names
    except OSError as exc:
        raise ConfigError([f"canonical skills directory {profile.skills_dir}: cannot inspect: {exc}"]) from None
    finally:
        os.close(handle.descriptor)


def _prepare_from_fd(
    profile: Profile,
    root_descriptor: int,
    *,
    recovery_paths: set[Path] | None = None,
) -> list[Prepared]:
    """Read and generate every target before any filesystem mutation."""
    prepared: list[Prepared] = []
    recovery = set(recovery_paths or ())
    seen: set[Path] = set()
    existing_skills = _existing_skill_names(profile, root_descriptor)
    ownership = _read_skills_manifest(root_descriptor)
    previously_managed = (
        set(ownership.managed_skills)
        if ownership.skills_dir == profile.skills_dir
        else set()
    )
    shadowed = existing_skills - previously_managed
    rendered_files = (
        render(profile)
        if not shadowed and not existing_skills
        else render(
            profile,
            shadowed_skills=shadowed,
            consumer_skills=shadowed,
            available_skills=existing_skills,
        )
    )
    for rendered in rendered_files:
        if rendered.path in seen:
            raise ConfigError([f"duplicate generated target: {rendered.path}"])
        seen.add(rendered.path)
        _validate_relative(rendered.path)
        state = _read_relative(
            root_descriptor, rendered.path, allow_symlink=rendered.symlink
        )
        original = state.content if state is not None else None
        mode = state.mode if state is not None else None
        expected = _expected(rendered, original)
        try:
            rendered.path.relative_to(profile.skills_dir)
            canonical_target = not rendered.symlink
        except ValueError:
            canonical_target = False
        if rendered.symlink and state is not None:
            if not state.symlink:
                raise ConfigError(
                    [f"{rendered.path}: consumer-owned regular file cannot be replaced by a mirror link"]
                )
            old_target = ownership.mirror_links.get(rendered.path)
            if old_target is None:
                if rendered.path not in recovery or state.content != expected:
                    raise ConfigError(
                        [f"{rendered.path}: existing unmanifested mirror link is consumer-owned"]
                    )
            elif state.content not in {os.fsencode(old_target), expected}:
                raise ConfigError(
                    [f"{rendered.path}: manifested mirror link target changed; refusing replacement"]
                )
        elif canonical_target and state is not None:
            old_digest = ownership.canonical_files.get(rendered.path)
            if old_digest is None:
                if rendered.path not in recovery or state.content != expected:
                    raise ConfigError(
                        [f"{rendered.path}: existing unmanifested file is consumer-owned"]
                    )
                old_digest = hashlib.sha256(state.content).hexdigest()
            current_digest = hashlib.sha256(state.content).hexdigest()
            if current_digest != old_digest and state.content != expected:
                raise ConfigError(
                    [f"{rendered.path}: manifested file digest changed; refusing replacement"]
                )
        prepared.append(
            Prepared(
                rendered,
                original,
                mode,
                expected,
                state.symlink if state is not None else False,
            )
        )
    return prepared


def _stale_owned_files(
    ownership: SkillsOwnership,
    root_descriptor: int,
    desired: set[Path],
) -> dict[Path, bytes]:
    stale: dict[Path, bytes] = {}
    for path, digest in ownership.canonical_files.items():
        if path in desired:
            continue
        state = _read_relative(root_descriptor, path)
        if state is None:
            continue
        if hashlib.sha256(state.content).hexdigest() != digest:
            raise ConfigError([f"{path}: stale manifested file digest changed; refusing deletion"])
        stale[path] = state.content
    return stale


def _stale_owned_directories(
    ownership: SkillsOwnership, desired_files: set[Path]
) -> list[Path]:
    desired_directories = {
        parent
        for path in desired_files
        for parent in path.parents
        if ownership.skills_dir is not None
        and parent != ownership.skills_dir
        and parent.is_relative_to(ownership.skills_dir)
    }
    return sorted(
        ownership.canonical_directories - desired_directories,
        key=lambda path: (-len(path.parts), path.as_posix()),
    )


def _remove_stale_directories(
    root_descriptor: int, directories: list[Path]
) -> None:
    for path in directories:
        parent = _open_parent(root_descriptor, path, create=False)
        if parent is None:
            continue
        try:
            metadata = os.stat(path.name, dir_fd=parent.descriptor, follow_symlinks=False)
            if stat.S_ISLNK(metadata.st_mode) or not stat.S_ISDIR(metadata.st_mode):
                raise ConfigError([f"{path}: manifested directory changed type; refusing deletion"])
            try:
                os.rmdir(path.name, dir_fd=parent.descriptor)
                os.fsync(parent.descriptor)
            except OSError as exc:
                if exc.errno != errno.ENOTEMPTY:
                    raise
        except FileNotFoundError:
            pass
        except OSError as exc:
            raise ConfigError([f"{path}: stale managed-directory removal failed: {exc}"]) from None
        finally:
            os.close(parent.descriptor)


def _prepare(profile: Profile) -> list[Prepared]:
    root_descriptor = _open_absolute_directory(profile.root)
    try:
        return _prepare_from_fd(profile, root_descriptor)
    finally:
        os.close(root_descriptor)


def expected_content(root: Path, rendered: Rendered) -> str:
    """Compatibility helper used by callers that need one validated render."""
    root = Path(root).resolve(strict=True)
    _safe_target(root, rendered.path)
    root_descriptor = _open_absolute_directory(root)
    try:
        state = _read_relative(root_descriptor, rendered.path, allow_symlink=rendered.symlink)
    finally:
        os.close(root_descriptor)
    return _expected(rendered, state.content if state is not None else None).decode("utf-8")


@contextmanager
def _locked_root(root: Path) -> Iterator[int]:
    """Open the repository and hold its repository-wide sync lock exclusively."""
    root_descriptor = _open_absolute_directory(root)
    lock_parent = _open_parent(root_descriptor, LOCK_PATH, create=True)
    assert lock_parent is not None
    lock_descriptor = -1
    try:
        try:
            lock_descriptor = os.open(
                LOCK_PATH.name,
                os.O_RDWR | os.O_CREAT | os.O_NOFOLLOW | os.O_CLOEXEC,
                0o644,
                dir_fd=lock_parent.descriptor,
            )
            if not stat.S_ISREG(os.fstat(lock_descriptor).st_mode):
                raise ConfigError([f"sync lock {LOCK_PATH}: must be a regular file"])
            fcntl.flock(lock_descriptor, fcntl.LOCK_EX)
        except OSError as exc:
            raise ConfigError([f"sync lock {LOCK_PATH}: unavailable: {exc}"]) from None
        yield root_descriptor
    finally:
        if lock_descriptor >= 0:
            os.close(lock_descriptor)
        os.close(lock_parent.descriptor)
        os.close(root_descriptor)


def _partial_exists(root_descriptor: int) -> bool:
    state = _read_relative(root_descriptor, PARTIAL_PATH)
    return state is not None


def _partial_targets(root_descriptor: int) -> set[Path]:
    state = _read_relative(root_descriptor, PARTIAL_PATH)
    if state is None:
        return set()
    try:
        payload = json.loads(state.content.decode("utf-8"))
        targets = payload["targets"]
        if payload.get("state") != "replacement-in-progress" or not isinstance(targets, list):
            raise ValueError("invalid replacement state")
        return {_manifest_relative_path(target, "partial target") for target in targets}
    except (KeyError, TypeError, ValueError, UnicodeError) as exc:
        raise ConfigError([f"{PARTIAL_PATH}: invalid interrupted-sync marker: {exc}"]) from None


def _partial_handle(root_descriptor: int) -> DirectoryHandle:
    handle = _open_parent(root_descriptor, PARTIAL_PATH, create=True)
    assert handle is not None
    return handle


def _write_partial(
    handle: DirectoryHandle, changed: list[Prepared], stale_links: dict[Path, str] | None = None
) -> None:
    _verify_directory(handle)
    payload = json.dumps(
        {
            "state": "replacement-in-progress",
            "targets": [str(item.rendered.path) for item in changed]
            + [str(path) for path in sorted(stale_links or {})],
        },
        indent=2,
        sort_keys=True,
    ).encode("utf-8") + b"\n"
    temporary = f".{PARTIAL_PATH.name}.{secrets.token_hex(12)}"
    descriptor = -1
    try:
        descriptor = os.open(
            temporary,
            os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW | os.O_CLOEXEC,
            0o600,
            dir_fd=handle.descriptor,
        )
        try:
            os.fchmod(descriptor, 0o644)
            offset = 0
            while offset < len(payload):
                offset += os.write(descriptor, payload[offset:])
            os.fsync(descriptor)
        finally:
            os.close(descriptor)
            descriptor = -1
        os.rename(
            temporary,
            PARTIAL_PATH.name,
            src_dir_fd=handle.descriptor,
            dst_dir_fd=handle.descriptor,
        )
        os.fsync(handle.descriptor)
    except OSError as exc:
        if descriptor >= 0:
            os.close(descriptor)
        try:
            os.unlink(temporary, dir_fd=handle.descriptor)
        except FileNotFoundError:
            pass
        raise ConfigError([f"interrupted-sync marker {PARTIAL_PATH}: cannot write: {exc}"]) from None


def _remove_partial(handle: DirectoryHandle) -> None:
    _verify_directory(handle)
    try:
        os.unlink(PARTIAL_PATH.name, dir_fd=handle.descriptor)
        os.fsync(handle.descriptor)
    except FileNotFoundError:
        pass
    except OSError as exc:
        raise ConfigError([f"interrupted-sync marker {PARTIAL_PATH}: cannot remove: {exc}"]) from None


def _stale_mirror_links(
    ownership: SkillsOwnership, root_descriptor: int, desired: set[Path]
) -> dict[Path, str]:
    stale: dict[Path, str] = {}
    for path, owned_target in ownership.mirror_links.items():
        if path in desired:
            continue
        state = _read_relative(root_descriptor, path, allow_symlink=True)
        if state is None:
            continue
        if not state.symlink:
            raise ConfigError([f"{path}: manifested mirror link changed type; refusing deletion"])
        current = os.fsdecode(state.content)
        if current != owned_target:
            raise ConfigError([f"{path}: manifested mirror link target changed; refusing deletion"])
        stale[path] = current
    return stale


def check(profile: Profile) -> list[Path]:
    """Return the paths whose checked-in content differs from the render."""
    with _locked_root(profile.root) as root_descriptor:
        if _partial_exists(root_descriptor):
            raise ConfigError(
                [f"interrupted sync: {PARTIAL_PATH} exists; run `loopzero sync` to recover"]
            )
        prepared = _prepare_from_fd(profile, root_descriptor)
        ownership = _read_skills_manifest(root_descriptor)
        drift = [
            item.rendered.path
            for item in prepared
            if item.original != item.expected
            or item.original_symlink != item.rendered.symlink
        ]
        desired_links = {item.rendered.path for item in prepared if item.rendered.symlink}
        desired_files = {
            item.rendered.path
            for item in prepared
            if not item.rendered.symlink
            and item.rendered.path != SKILLS_MANIFEST_PATH
            and item.rendered.path.is_relative_to(profile.skills_dir)
        }
        drift.extend(sorted(_stale_owned_files(ownership, root_descriptor, desired_files)))
        drift.extend(sorted(_stale_mirror_links(ownership, root_descriptor, desired_links)))
        return drift


def _stage(item: Prepared, parent: DirectoryHandle) -> str:
    _verify_directory(parent)
    temporary = f".{item.rendered.path.name}.{secrets.token_hex(12)}"
    if item.rendered.symlink:
        try:
            os.symlink(os.fsdecode(item.expected), temporary, dir_fd=parent.descriptor)
        except BaseException:
            try:
                os.unlink(temporary, dir_fd=parent.descriptor)
            except FileNotFoundError:
                pass
            raise
        return temporary
    descriptor = -1
    try:
        descriptor = os.open(
            temporary,
            os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW | os.O_CLOEXEC,
            0o600,
            dir_fd=parent.descriptor,
        )
        os.fchmod(descriptor, item.original_mode if item.original_mode is not None else 0o644)
        offset = 0
        while offset < len(item.expected):
            offset += os.write(descriptor, item.expected[offset:])
        os.fsync(descriptor)
    except BaseException:
        if descriptor >= 0:
            os.close(descriptor)
        try:
            os.unlink(temporary, dir_fd=parent.descriptor)
        except FileNotFoundError:
            pass
        raise
    else:
        os.close(descriptor)
    return temporary


def _verify_reachable(root_descriptor: int, handle: DirectoryHandle) -> None:
    probe = _open_parent(root_descriptor, handle.relative / "probe", create=False)
    if probe is None:
        raise ConfigError([f"generated parent {handle.relative}: disappeared concurrently"])
    try:
        if probe.identity != handle.identity:
            raise ConfigError([f"generated parent {handle.relative}: changed concurrently"])
    finally:
        os.close(probe.descriptor)


def _verify_root_path(root: Path, root_descriptor: int) -> None:
    probe = _open_absolute_directory(root)
    try:
        if _identity(os.fstat(probe)) != _identity(os.fstat(root_descriptor)):
            raise ConfigError(["repository root changed concurrently"])
    finally:
        os.close(probe)


def write(profile: Profile) -> list[Path]:
    """Write every rendered file; return the paths that changed."""
    with _locked_root(profile.root) as root_descriptor:
        had_partial = _partial_exists(root_descriptor)
        recovery_paths = _partial_targets(root_descriptor) if had_partial else set()
        prepared = _prepare_from_fd(
            profile, root_descriptor, recovery_paths=recovery_paths
        )
        ownership = _read_skills_manifest(root_descriptor)
        changed = [
            item
            for item in prepared
            if item.original != item.expected
            or item.original_symlink != item.rendered.symlink
        ]
        desired_links = {item.rendered.path for item in prepared if item.rendered.symlink}
        desired_files = {
            item.rendered.path
            for item in prepared
            if not item.rendered.symlink
            and item.rendered.path != SKILLS_MANIFEST_PATH
            and item.rendered.path.is_relative_to(profile.skills_dir)
        }
        stale_files = _stale_owned_files(ownership, root_descriptor, desired_files)
        stale_directories = _stale_owned_directories(ownership, desired_files)
        stale_links = _stale_mirror_links(ownership, root_descriptor, desired_links)
        partial_parent = _partial_handle(root_descriptor)
        if not changed and not stale_links and not stale_files:
            try:
                if had_partial:
                    _remove_partial(partial_parent)
                return []
            finally:
                os.close(partial_parent.descriptor)

        parents: dict[Path, DirectoryHandle] = {partial_parent.relative: partial_parent}
        staged: list[tuple[Prepared, DirectoryHandle, str]] = []
        completed = False
        try:
            for item in prepared:
                relative_parent = item.rendered.path.parent
                if relative_parent not in parents:
                    handle = _open_parent(root_descriptor, item.rendered.path, create=True)
                    assert handle is not None
                    parents[relative_parent] = handle
            for path in stale_links:
                if path.parent not in parents:
                    handle = _open_parent(root_descriptor, path, create=False)
                    assert handle is not None
                    parents[path.parent] = handle
            for path in stale_files:
                if path.parent not in parents:
                    handle = _open_parent(root_descriptor, path, create=False)
                    assert handle is not None
                    parents[path.parent] = handle
            for item in changed:
                parent = parents[item.rendered.path.parent]
                staged.append((item, parent, _stage(item, parent)))

            # Re-read every render-time input through the anchored directory
            # descriptors. Honest concurrent syncs cannot enter this section
            # because they hold the same flock.
            _verify_root_path(profile.root, root_descriptor)
            for parent in parents.values():
                _verify_reachable(root_descriptor, parent)
            for item in prepared:
                state = _read_name(
                    parents[item.rendered.path.parent],
                    item.rendered.path.name,
                    item.rendered.path,
                    allow_symlink=item.rendered.symlink,
                )
                current = state.content if state is not None else None
                current_mode = state.mode if state is not None else None
                current_symlink = state.symlink if state is not None else False
                if (
                    current != item.original
                    or current_mode != item.original_mode
                    or current_symlink != item.original_symlink
                ):
                    raise ConfigError(
                        [f"{item.rendered.path}: changed concurrently; no files written"]
                    )
            current_stale_files = _stale_owned_files(
                ownership, root_descriptor, desired_files
            )
            if current_stale_files != stale_files:
                raise ConfigError(["managed skill files changed concurrently; no files written"])
            current_stale = _stale_mirror_links(ownership, root_descriptor, desired_links)
            if current_stale != stale_links:
                raise ConfigError(["skill mirror links changed concurrently; no files written"])

            _write_partial(
                partial_parent, changed, {**stale_links, **{path: "file" for path in stale_files}}
            )
            manifest_staged: tuple[int, Prepared, DirectoryHandle, str] | None = None
            for index, (item, parent, temporary) in enumerate(staged):
                if item.rendered.path == SKILLS_MANIFEST_PATH:
                    manifest_staged = (index, item, parent, temporary)
                    continue
                _verify_directory(parent)
                try:
                    os.rename(
                        temporary,
                        item.rendered.path.name,
                        src_dir_fd=parent.descriptor,
                        dst_dir_fd=parent.descriptor,
                    )
                except OSError as exc:
                    raise ConfigError(
                        [
                            f"{item.rendered.path}: replacement failed; "
                            f"interrupted-sync marker retained: {exc}"
                        ]
                    ) from None
                os.fsync(parent.descriptor)
                staged[index] = (item, parent, "")
            for path in sorted(stale_files):
                parent = parents[path.parent]
                _verify_directory(parent)
                try:
                    os.unlink(path.name, dir_fd=parent.descriptor)
                    os.fsync(parent.descriptor)
                except FileNotFoundError:
                    pass
                except OSError as exc:
                    raise ConfigError(
                        [f"{path}: stale managed-file removal failed; interrupted-sync marker retained: {exc}"]
                    ) from None
            for path in sorted(stale_links):
                parent = parents[path.parent]
                _verify_directory(parent)
                try:
                    os.unlink(path.name, dir_fd=parent.descriptor)
                    os.fsync(parent.descriptor)
                except OSError as exc:
                    raise ConfigError(
                        [
                            f"{path}: stale mirror removal failed; "
                            f"interrupted-sync marker retained: {exc}"
                        ]
                    ) from None
            _remove_stale_directories(root_descriptor, stale_directories)
            if manifest_staged is not None:
                index, item, parent, temporary = manifest_staged
                _verify_directory(parent)
                try:
                    os.rename(
                        temporary,
                        item.rendered.path.name,
                        src_dir_fd=parent.descriptor,
                        dst_dir_fd=parent.descriptor,
                    )
                    os.fsync(parent.descriptor)
                    staged[index] = (item, parent, "")
                except OSError as exc:
                    raise ConfigError(
                        [f"{item.rendered.path}: replacement failed; interrupted-sync marker retained: {exc}"]
                    ) from None
            _remove_partial(partial_parent)
            completed = True
            return (
                [item.rendered.path for item in changed]
                + sorted(stale_files)
                + sorted(stale_links)
            )
        finally:
            for _, parent, temporary in staged:
                if temporary:
                    try:
                        os.unlink(temporary, dir_fd=parent.descriptor)
                    except FileNotFoundError:
                        pass
            for parent in parents.values():
                os.close(parent.descriptor)
            if not completed:
                created_directories = sorted(
                    {
                        path
                        for parent in parents.values()
                        for path in parent.created
                    },
                    key=lambda path: (-len(path.parts), path.as_posix()),
                )
                try:
                    _remove_stale_directories(root_descriptor, created_directories)
                except ConfigError:
                    # Preserve the original preparation/replacement error. A
                    # nonempty or concurrently changed directory is safer left
                    # in place and is covered by the partial marker after writes.
                    pass
